"""Interface data for the user-built concrete base (R-I2) and the separate roof project (R-I1),
computed from the CAD model. Run: uv run python -m geometry.interfaces -> docs/interfaces.md"""

from __future__ import annotations

from pathlib import Path

from geometry.oven_b import OvenB, Params
from materials import db

OUT = Path(__file__).resolve().parents[1] / "docs" / "interfaces.md"


def masses(ov: OvenB, mats) -> dict:
    out: dict[str, float] = {}
    for pt in ov.parts:
        rho = mats[pt.material]["density"].at(300.0)
        out[pt.family] = out.get(pt.family, 0.0) + pt.volume_m3 * rho
    return out


def main():
    p = Params()
    mats = db.load()
    ov = OvenB(p).build()
    m = masses(ov, mats)
    total = sum(m.values())
    bb = None
    for pt in ov.parts:
        b = pt.solid.val().BoundingBox()
        bb = b if bb is None else bb.add(b)
    x_out = p.x_wall_out + p.ins_t + p.shell_t
    L0, L1 = p.y_front_out - p.ins_t, p.y_back_out + p.ins_t
    a = p.arch
    lines = [
        "# Interfaces (generated by `geometry/interfaces.py`)", "",
        "Coordinates: x across (0 = oven centre line), y front-to-back (0 = front edge of the cooking floor), "
        "z up (0 = top of the concrete base). Millimetres.", "",
        "## R-I2: concrete base (built by the user)", "",
        f"- **Oven footprint on the base** (shell + frame): x {-x_out-p.ang:.0f} … {x_out+p.ang:.0f}, "
        f"y {L0-p.ang:.0f} … {L1+p.ang:.0f} → **{2*(x_out+p.ang):.0f} × {L1-L0+2*p.ang:.0f} mm**.",
        f"- **Recommended base top**: at least {2*(x_out+p.ang)+100:.0f} × {L1-L0+2*p.ang+300:.0f} mm "
        "(50 mm margin at the sides and back, a 250 mm landing in front of the door for the peel and tools).",
        f"- **Cooking floor height** = base top + {p.z_floor:.0f} mm. A common Neapolitan working height is about elbow height; "
        "choose the base height for the main user.",
        f"- **Oven mass** (from the CAD model and sourced densities): **{total:.0f} kg**, of which bricks "
        f"{sum(v for k, v in m.items() if 'brick' in k):.0f} kg. Allow for people leaning on it: design the base for at least "
        f"{1.5*total:.0f} kg spread over the footprint (1.5 × self-weight, an allowance, not a code value).",
        f"- **Anchors**: 4 buckstay foot cleats, 2 × M12 each, at x = ±{x_out+p.ang/2:.0f}, y = {L0-p.ang/2:.0f} and {L1+p.ang/2:.0f}. "
        "Keep reinforcement and edges at least 100 mm away from the anchor holes.",
        "- **Temperature**: the top of the concrete under the floor insulation reaches about 80–110 °C in long sessions "
        "(see `docs/reports/phase-3.md`). The 100 °C limit is an ASSUMPTION (K-28). Use ordinary concrete. Let it cure "
        "for at least 28 days, and dry before the first firing. Do not seal the top with plastic.",
        "- **Water**: slope the top 1–2 % to the sides, or cast a 10 mm drip groove around the edge, so rain runoff does not "
        "collect under the floor insulation.", "",
        "## R-I1: roof (separate project)", "",
        f"- **Flue**: Ø{p.flue_d:.0f} mm black-steel stove pipe, centre at x = 0, y = {L0 - p.panel_t - p.hood_depth/2:.0f}, starting at "
        f"z = {p.z_floor + p.door_h + 160:.0f} mm above the base (top of the hood collar). The pipe carries gas at roughly "
        "200–650 °C (model gas temperature during firing), so treat it as a hot flue.",
        "- **Clearances**: follow the stove-pipe manufacturer's clearance to combustibles. Where the pipe passes a roof, "
        "use a certified double-wall (insulated) section and roof flashing. **Do not build a closed shelter**: the oven must "
        "stay in open air (R-S2, carbon monoxide).",
        f"- **Oven envelope**: {bb.xlen:.0f} (w) × {bb.ylen:.0f} (d) × {bb.zlen:.0f} (h) mm including the hood and 1 m pipe. "
        f"Shell top {a['z_c']+a['R_e']+p.ins_t+p.shell_t:.0f} mm above the base. Leave at least 600 mm of free space in front "
        "for working with the peel.",
        "- **Rain**: the shell and end panels shed rain, but the insulation must stay dry (K-06). The roof should keep "
        "driving rain off the door and hood area.", "",
        "## Mass by family (kg)", "",
        "| Family | kg |", "|---|---|",
    ] + [f"| {k} | {v:.1f} |" for k, v in sorted(m.items(), key=lambda kv: -kv[1])]
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
